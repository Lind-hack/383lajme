// Generates lib/tone-map-paths.ts — the inset map's geometry, baked.
//
// Run by hand, never at build or request time:
//     node scripts/build-map-paths.mjs
//
// The repo has no charting or mapping dependency and three separate source
// comments say that is deliberate, so the geometry is pre-projected here and
// the committed output is a plain string table. Nothing ships but path data.
//
// Source: Natural Earth 110m admin-0, public domain, no attribution required.

import { writeFileSync } from "node:fs";

const SRC =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson";

// Europe-weighted crop. The old one ran to -128 to fit the continental US,
// which spent forty percent of the frame on empty Atlantic and squeezed
// Europe — where fourteen of the fifteen tracked countries live — into a
// thumbnail. This keeps the US eastern seaboard in frame and gives Europe
// roughly four times the pixels it had.
const LON0 = -88, LON1 = 42;
const LAT0 = 30, LAT1 = 64;
const W = 1000;

// The fifteen editions the scraper reads. Everything else in frame is drawn
// as recessive context so the map reads as a place, not a chart of holes.
const TRACKED = new Set([
  "US", "GB", "FR", "DE", "IT", "AT", "CH",
  "NL", "BE", "ES", "GR", "SE", "PL", "TR", "HR",
]);

const rad = (d) => (d * Math.PI) / 180;
const merc = (lat) => Math.log(Math.tan(Math.PI / 4 + rad(lat) / 2));

const yTop = merc(LAT1), yBot = merc(LAT0);
// Uniform scale: derive the height rather than picking one and shearing.
const H = Math.round((W * (yTop - yBot)) / rad(LON1 - LON0));

const project = ([lon, lat]) => {
  const x = ((lon - LON0) / (LON1 - LON0)) * W;
  const y = ((yTop - merc(Math.max(-85, Math.min(85, lat)))) / (yTop - yBot)) * H;
  return [x, y];
};

/** Keep a ring only if some of it is actually on screen. */
const onScreen = (pts) =>
  pts.some(([x, y]) => x > -40 && x < W + 40 && y > -40 && y < H + 40);

/** Smallest on-screen box a ring must fill to be worth shipping, in viewBox
 *  units. At 1000 wide this drops islets that render as a speck or less. */
const MIN_RING_PX = 2.5;

function ringToPath(ring) {
  const pts = ring.map(project);
  if (pts.length < 4 || !onScreen(pts)) return "";
  const xs = pts.map((p) => p[0]);
  const ys = pts.map((p) => p[1]);
  const w = Math.max(...xs) - Math.min(...xs);
  const h = Math.max(...ys) - Math.min(...ys);
  if (Math.max(w, h) < MIN_RING_PX) return "";
  const out = [];
  let last = null;
  for (const [x, y] of pts) {
    // Whole viewBox units. At 1000 wide rendered around 700px that is ~0.7px,
    // finer than anything visible, and dedupe-after-rounding collapses runs.
    const p = `${x.toFixed(0)},${y.toFixed(0)}`;
    if (p !== last) out.push(p);
    last = p;
  }
  if (out.length < 4) return "";
  return `M${out.join("L")}Z`;
}

function featureToPath(geom) {
  const polys =
    geom.type === "Polygon" ? [geom.coordinates]
    : geom.type === "MultiPolygon" ? geom.coordinates
    : [];
  return polys
    .flatMap((poly) => poly.map(ringToPath))
    .filter(Boolean)
    .join("");
}

const res = await fetch(SRC);
if (!res.ok) throw new Error(`Natural Earth fetch failed: ${res.status}`);
const { features } = await res.json();

const rows = [];
for (const f of features) {
  const p = f.properties;
  const code = (p.ISO_A2_EH || p.ISO_A2 || "").toUpperCase();
  const d = featureToPath(f.geometry);
  if (!d) continue;
  rows.push({ code, name: p.NAME || p.ADMIN || code, tracked: TRACKED.has(code), d });
}

// Tracked countries last so they paint over the context layer.
rows.sort((a, b) => Number(a.tracked) - Number(b.tracked));

const missing = [...TRACKED].filter((c) => !rows.some((r) => r.code === c && r.tracked));
if (missing.length) throw new Error(`tracked country missing from source: ${missing.join(", ")}`);

const body = rows
  .map((r) => `  { code: ${JSON.stringify(r.code)}, tracked: ${r.tracked}, d: ${JSON.stringify(r.d)} },`)
  .join("\n");

writeFileSync(
  new URL("../lib/tone-map-paths.ts", import.meta.url),
  `// GENERATED by scripts/build-map-paths.mjs — do not edit by hand.
// Natural Earth 110m admin-0, public domain, Mercator, cropped to the North
// Atlantic. \`tracked\` marks the countries the tone scraper covers;
// everything else is context and is drawn recessively.

export const MAP_VIEWBOX = { width: ${W}, height: ${H} } as const;

export interface MapShape {
  /** ISO 3166-1 alpha-2. */
  code: string;
  tracked: boolean;
  d: string;
}

export const MAP_SHAPES: MapShape[] = [
${body}
];
`,
  "utf-8"
);

const bytes = rows.reduce((n, r) => n + r.d.length, 0);
console.log(`wrote lib/tone-map-paths.ts — ${rows.length} shapes, viewBox ${W}x${H}, ${(bytes / 1024).toFixed(0)}KB of path data`);
