/**
 * Build the user turn: the question, and the sources it may be answered from.
 *
 * Sources are numbered from 1 because the model cites them by number and
 * zero-based citation invites an off-by-one that the validator would then
 * reject as invalid, turning a good answer into a refusal.
 */
export function buildPrompt(question, sources, opts = {}) {
  const { pinnedNote = true, history = [], name = null, today = "" } = opts;
  // Fewer sources means each may be read more fully. The cause of an event
  // sits in the last third of a news article, so a source cut short is a
  // source that cannot answer "why".
  const budget = sourceBudget(sources.length);
  const blocks = sources.map((entry, i) => {
    const a = entry.article;
    const head = `[${i + 1}] ${a.title}`;
    const when = a.meta ? ` (${a.meta})` : "";
    const marker = pinnedNote && entry.pinned ? "  ← artikulli që po lexon përdoruesi" : "";
    return `${head}${when}${marker}\n${trimSource(a, budget)}`;
  });

  // Earlier turns, so a follow-up like "po pse?" is read as part of a
  // conversation rather than as a question about nothing.
  const past = history.length
    ? `BISEDA DERI TANI:\n${history
        .map((t) => `Lexuesi: ${t.question}\nDardani: ${t.answer}`)
        .join("\n\n")}\n\n`
    : "";

  // "Sot", "dje" and "javën e kaluar" mean nothing to a model without a date.
  const about = [today ? `Sot është ${today}.` : null, name ? `Emri i lexuesit: ${name}.` : null]
    .filter(Boolean)
    .join(" ");

  return `${about ? `${about}\n\n` : ""}${past}PYETJA E LEXUESIT:\n${question}\n\nARTIKUJT E BOTUAR TE 383:\n\n${blocks.join("\n\n---\n\n")}`;
}

/**
 * Decide whether what came back may be shown.
 *
 * Returns either a grounded answer with the citations resolved to real
 * sources, or a refusal. There is no third outcome, and no path that shows
 * model text without at least one valid citation behind it.
 */
export function validateAnswer(raw, sourceCount) {
  if (!raw || typeof raw !== "object") return { grounded: false, reason: "no-json" };
  if (raw.enough === false) return { grounded: false, reason: "model-declined" };

  const answer = typeof raw.answer === "string" ? raw.answer.trim() : "";
  if (answer.length < 12) return { grounded: false, reason: "empty-answer" };
  // A model that ignores "2–4 fjali" this badly has stopped following the
  // prompt, and the citation check is not worth trusting on the same output.
  if (answer.length > 1600) return { grounded: false, reason: "runaway-answer" };

  const cited = Array.isArray(raw.sources) ? raw.sources : [];
  const valid = [];
  for (const value of cited) {
    const n = typeof value === "number" ? value : Number.parseInt(String(value), 10);
    if (!Number.isInteger(n) || n < 1 || n > sourceCount) continue;
    if (!valid.includes(n)) valid.push(n);
  }

  // The gate. No verifiable source, no answer — however plausible it reads.
  if (valid.length === 0) return { grounded: false, reason: "no-valid-citation" };

  return { grounded: true, answer, sources: valid, followups: cleanFollowups(raw.followups) };
}

/** Albanian number words a model may turn into digits ("dy ditë" → "2 ditë"). */
const NUMBER_WORDS = {
  nje: "1", dy: "2", tre: "3", tri: "3", kater: "4", pese: "5", gjashte: "6",
  shtate: "7", tete: "8", nente: "9", dhjete: "10", njezet: "20", qind: "100",
};

/** Every number in a text, normalised so "14,5", "14.5" and "1.200" compare. */
function numbersIn(text) {
  const out = new Set();
  const plain = String(text ?? "")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase();
  for (const raw of plain.match(/\d+(?:[.,\s]\d{3})*(?:[.,]\d+)?/g) ?? []) {
    const n = raw.replace(/\s/g, "");
    out.add(n.replace(/[.,](?=\d{3}\b)/g, "").replace(",", "."));
    out.add(n.replace(/\D/g, ""));
  }
  for (const word of plain.match(/[a-z]+/g) ?? []) {
    if (NUMBER_WORDS[word]) out.add(NUMBER_WORDS[word]);
  }
  return out;
}

/**
 * Numbers in the answer that appear nowhere it was allowed to take them from.
 *
 * A citation proves the model was handed an article, not that the figure it
 * wrote is the article's. A wrong number is the most damaging small error a
 * news bot makes and the easiest to check, so it is checked: every number in
 * the answer must occur in a cited source, the question, the thread or today's
 * date. Words are not checked the same way: Albanian declension makes a name
 * check either useless or a refusal machine.
 */
export function unsupportedNumbers(answer, allowedTexts) {
  const allowed = new Set();
  for (const text of allowedTexts) for (const n of numbersIn(text)) allowed.add(n);
  const missing = [];
  const plain = String(answer ?? "");
  for (const raw of plain.match(/\d+(?:[.,\s]\d{3})*(?:[.,]\d+)?/g) ?? []) {
    const n = raw.replace(/\s/g, "");
    const forms = [n.replace(/[.,](?=\d{3}\b)/g, "").replace(",", "."), n.replace(/\D/g, "")];
    if (!forms.some((f) => allowed.has(f))) missing.push(raw.trim());
  }
  return missing;
}
