const BY_CITY_AND_NAME = new Map(PLACES.map((p) => [`${p.cityId}|${p.name}`, p]));

/** The visit hint in the visitor's language ("1-3 orë" → "1-3 h"). */
export function localizedHint(hint, lang) {
  if (lang !== "en") return hint;
  if (/gjysm/i.test(hint)) return "Half a day";
  if (/program/i.test(hint)) return "Depends on the programme";
  return hint.replace(/\s*orë/, " h");
}

/** Category, description and hint for a curated place, in the visitor's language. */
export function localizedPlace(cityId, place, lang) {
  const entry = BY_CITY_AND_NAME.get(`${cityId}|${place.name}`);
  const pick = (field, fallback) => (entry ? entry[field][lang === "en" ? "en" : "sq"] : fallback);
  return {
    category: pick("category", place.category),
    description: pick("description", place.description),
    visitHint: localizedHint(place.visitHint, lang),
  };
}

export function localizedCity(cityId, city, lang) {
  const text = CITY_TEXT[cityId];
  const key = lang === "en" ? "en" : "sq";
  return { region: text ? text.region[key] : city.region, tagline: text ? text.tagline[key] : city.tagline };
}
